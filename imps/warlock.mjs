#!/usr/bin/env node
// Topology guard for the imps kit. Contract: WARLOCK.md.
//
//   node warlock.mjs [--json]
//
// Reads only local state and never mutates anything: one line per check, exit
// 1 if any fail. The point is to catch the two silent breaks — a runner that
// is not a git checkout, and a second warlock on the same machine — before
// they turn into unexplainable gate failures.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { resolveRouter, describeRouter } from './lib.mjs';

const HOME = process.env.IMPS_HOME || join(homedir(), '.imps');
const CODE = process.env.IMPS_CODE || join(homedir(), 'code');
const KIT_POINTER = join(HOME, 'kit-path.txt');
// dispatch.mjs skips a cycle while the lock is younger than this.
const STALE_LOCK_MS = 3 * 3600_000;

export function countDispatchSchedulers(cronLines, hourlyPath, systemdActive) {
    const cron = cronLines.filter((line) => line.trim() && !line.trimStart().startsWith('#') && line.includes(hourlyPath));
    const names = cron.map((_, i) => 'cron: hourly.sh' + (cron.length > 1 ? ' #' + (i + 1) : ''));
    if (systemdActive) names.push('systemd: imps-hourly.timer');
    return { count: names.length, names };
}
const results = [];
const check = (name, ok, detail) => results.push({ name, ok, detail });
const git = (args, cwd) => spawnSync('git', args, { cwd, encoding: 'utf8', windowsHide: true });

function read(p) {
    try {
        return readFileSync(p, 'utf8');
    } catch {
        return null;
    }
}

// ── the runner must be a clone we can reset ───────────────────────────────
const runner = (read(KIT_POINTER) || process.env.IMPS_KIT_PATH || '').trim();
if (!runner) {
    check('runner path known', false, `no ${KIT_POINTER} and no $env:IMPS_KIT_PATH`);
} else {
    const dispatch = join(runner, 'imps', 'dispatch.mjs');
    const isRepo = existsSync(join(runner, '.git'));
    check('runner is a git checkout', isRepo, isRepo ? runner : `${runner} has no .git — re-run setup.ps1 with a fresh -RunnerPath`);
    check('runner has imps/dispatch.mjs', existsSync(dispatch), existsSync(dispatch) ? dispatch : `${dispatch} is missing`);

    if (isRepo) {
        // Tracked changes only, matching what update/setup actually refuse on:
        // an untracked file survives `reset --hard` and blocks nothing (#59).
        const st = git(['status', '--porcelain', '--untracked-files=no'], runner);
        const real = (st.stdout || '').trim().split('\n').filter((l) => l.trim());
        check('runner has no local edits', !real.length, real.length ? `${real.length} changed file(s) — setup.ps1 will refuse to reset: ${real[0].trim()}` : 'clean');

        const branch = (git(['rev-parse', '--abbrev-ref', 'HEAD'], runner).stdout || '').trim();
        const behind = (git(['rev-list', '--count', 'HEAD..origin/main'], runner).stdout || '').trim();
        check('runner is current with origin/main', branch === 'main' && behind === '0', branch !== 'main' ? `on ${branch || '?'}, expected a detached checkout of origin/main` : `${behind || '?'} commit(s) behind`);
    }
}

// ── hourly.cmd/.sh must launch the same runner ──────────────────────────────
const hourly = process.platform === 'win32' ? join(HOME, 'hourly.cmd') : join(HOME, 'hourly.sh');
const hourlyBody = read(hourly);
if (!hourlyBody) {
    check(`${process.platform === 'win32' ? 'hourly.cmd' : 'hourly.sh'} exists`, false, `${hourly} missing — run setup.ps1 or setup.sh`);
} else {
    const m = hourlyBody.match(/set IMPS_KIT_PATH=(.+)/i) || hourlyBody.match(/export IMPS_KIT_PATH=(.+)/i);
    let pointed = m ? m[1].trim().replace(/\r$/, '') : null;
    // Setup may quote the value (Unix wrapper). Strip surrounding quotes.
    if (pointed && ((pointed.startsWith('"') && pointed.endsWith('"')) || (pointed.startsWith("'") && pointed.endsWith("'")))) {
        pointed = pointed.slice(1, -1);
    }
    check(`${process.platform === 'win32' ? 'hourly.cmd' : 'hourly.sh'} points at the runner`, Boolean(pointed) && pointed === runner, pointed ? pointed : 'no IMPS_KIT_PATH line — it will run whatever cwd it inherits');

    // The generated wrapper is stamped with the setup sha it came from. An old
    // wrapper keeps running old logic (missing preflight, missing reset check)
    // even though the kit checkout itself is current — invisible otherwise.
    const stamped = (hourlyBody.match(/Generated by imps\/setup\.(ps1|sh) from ([a-f0-9]+)/i) || [])[2] || null;
    const head = (git(['rev-parse', '--short', 'HEAD'], runner).stdout || '').trim();
    if (!stamped) {
        check(`${process.platform === 'win32' ? 'hourly.cmd' : 'hourly.sh'} is current`, false, 'no "Generated by imps/setup" stamp — re-run setup to pick up the reset check and preflight');
    } else {
        check(`${process.platform === 'win32' ? 'hourly.cmd' : 'hourly.sh'} is current`, !head || stamped === head, stamped === head ? stamped : `generated from ${stamped}, runner is at ${head || '?'} — re-run setup.ps1/-sh`);
    }
}

// ── exactly one warlock per machine ───────────────────────────────────────
if (process.platform !== 'win32') {
    // Check cron for hourly.sh
    let cronLines = [];
    let cronMismatch = false;
    try {
        const cron = spawnSync('crontab', ['-l'], { encoding: 'utf8', windowsHide: true });
        if (cron.status === 0) {
            cronLines = (cron.stdout || '').split(/\r?\n/);
            cronMismatch = cronLines.some((line) => line.trim() && !line.trimStart().startsWith('#') && line.includes('hourly.sh') && !line.includes(hourly));
        }
    } catch { /* crontab not available */ }

    // Check systemd timers
    let systemdExists = false;
    let systemdCurrent = false;
    try {
        const timer = spawnSync('systemctl', ['--user', 'list-timers', '--no-legend'], { encoding: 'utf8', windowsHide: true });
        if (timer.status === 0) {
            const lines = (timer.stdout || '').split('\n');
            const impsTimer = lines.find(l => l.includes('imps-hourly'));
            systemdExists = Boolean(impsTimer);
            // Check the service ExecStart
            if (impsTimer) {
                const svc = spawnSync('systemctl', ['--user', 'show', 'imps-hourly.service', '-p', 'ExecStart'], { encoding: 'utf8', windowsHide: true });
                const execStart = (svc.stdout || '').trim().replace('ExecStart=', '');
                systemdCurrent = execStart.includes(hourly);
            }
        }
    } catch { /* systemctl not available */ }

    // Also check label-watch wrapper (optional but if present, should point to the right runner)
    const watch = join(HOME, 'label-watch.sh');
    const watchBody = read(watch);
    let watchCronExists = false;
    let watchCronCurrent = false;
    let watchSystemdExists = false;
    let watchSystemdCurrent = false;
    if (watchBody) {
        // Check cron for label-watch.sh
        try {
            const cron = spawnSync('crontab', ['-l'], { encoding: 'utf8', windowsHide: true });
            if (cron.status === 0) {
                const lines = (cron.stdout || '').split('\n');
                const watchLine = lines.find(l => l.includes('label-watch.sh'));
                watchCronExists = Boolean(watchLine);
                watchCronCurrent = watchLine ? watchLine.includes(watch) : false;
            }
        } catch { /* crontab not available */ }
        // Check systemd for label-watch
        try {
            const timer = spawnSync('systemctl', ['--user', 'list-timers', '--all', '--no-legend'], { encoding: 'utf8', windowsHide: true });
            if (timer.status === 0) {
                const lines = (timer.stdout || '').split('\n');
                const watchTimer = lines.find(l => l.includes('imps-label-watch'));
                watchSystemdExists = Boolean(watchTimer);
                if (watchTimer) {
                    const svc = spawnSync('systemctl', ['--user', 'show', 'imps-label-watch.service', '-p', 'ExecStart'], { encoding: 'utf8', windowsHide: true });
                    const execStart = (svc.stdout || '').trim().replace('ExecStart=', '');
                    watchSystemdCurrent = execStart.includes(watch);
                }
            }
        } catch { /* systemctl not available */ }
    }

    // Check groomer wrapper
    const groom = join(HOME, 'groom.sh');
    const groomBody = read(groom);
    let groomCronExists = false;
    let groomCronCurrent = false;
    let groomSystemdExists = false;
    let groomSystemdCurrent = false;
    if (groomBody) {
        // Check cron for groom.sh
        try {
            const cron = spawnSync('crontab', ['-l'], { encoding: 'utf8', windowsHide: true });
            if (cron.status === 0) {
                const lines = (cron.stdout || '').split('\n');
                const groomLine = lines.find(l => l.includes('groom.sh'));
                groomCronExists = Boolean(groomLine);
                groomCronCurrent = groomLine ? groomLine.includes(groom) : false;
            }
        } catch { /* crontab not available */ }
        // Check systemd for groomer
        try {
            const timer = spawnSync('systemctl', ['--user', 'list-timers', '--all', '--no-legend'], { encoding: 'utf8', windowsHide: true });
            if (timer.status === 0) {
                const lines = (timer.stdout || '').split('\n');
                const groomTimer = lines.find(l => l.includes('imps-groom'));
                groomSystemdExists = Boolean(groomTimer);
                if (groomTimer) {
                    const svc = spawnSync('systemctl', ['--user', 'show', 'imps-groom.service', '-p', 'ExecStart'], { encoding: 'utf8', windowsHide: true });
                    const execStart = (svc.stdout || '').trim().replace('ExecStart=', '');
                    groomSystemdCurrent = execStart.includes(groom);
                }
            }
        } catch { /* systemctl not available */ }
    }

    const topology = countDispatchSchedulers(cronLines, hourly, systemdExists && systemdCurrent);
    const watchDetail = watchBody ? (watchCronExists && watchCronCurrent ? 'cron: label-watch.sh' : watchCronExists ? 'cron: ' + watch + ' (mismatch)' : '') + (watchSystemdExists && watchSystemdCurrent ? 'systemd: imps-label-watch.timer' : watchSystemdExists ? 'systemd: ' + watch + ' (mismatch)' : '') : '';
    const groomDetail = groomBody ? (groomCronExists && groomCronCurrent ? 'cron: groom.sh' : groomCronExists ? 'cron: ' + groom + ' (mismatch)' : '') + (groomSystemdExists && groomSystemdCurrent ? 'systemd: imps-groom.timer' : groomSystemdExists ? 'systemd: ' + groom + ' (mismatch)' : '') : '';
    const detail = [topology.names.join('; '), cronMismatch ? 'cron: hourly.sh (path mismatch)' : '', systemdExists && !systemdCurrent ? 'systemd: ' + hourly + ' (mismatch)' : '', watchDetail, groomDetail].filter(Boolean).join('; ') || 'no active dispatch scheduler';
    check('exactly one dispatch task', topology.count === 1, detail);
} else {
    const ps = [
        'Get-ScheduledTask | Where-Object { $_.Actions | Where-Object { "$($_.Execute) $($_.Arguments)" -match "hourly\\.cmd|dispatch\\.mjs" } }',
        '| ForEach-Object { $_.TaskName }',
    ].join(' ');
    const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', ps], { encoding: 'utf8', windowsHide: true });
    const tasks = (r.stdout || '').split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
    check('exactly one dispatch task', tasks.length === 1, tasks.length ? tasks.join(', ') : 'no Scheduled Task runs a dispatcher — nothing is reading the queue');

    // Check groomer Scheduled Task
    const groomPs = 'Get-ScheduledTask -TaskName "imps-groom" -ErrorAction SilentlyContinue | Select-Object -ExpandProperty TaskName';
    const groomResult = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', groomPs], { encoding: 'utf8', windowsHide: true });
    const groomTask = (groomResult.stdout || '').trim();
    const groomExists = groomTask === 'imps-groom';
    check('groomer task registered', groomExists, groomExists ? 'imps-groom' : 'imps-groom not found — run setup.ps1 to register daily groomer');
}

// ── a cycle that died leaves the lock behind ──────────────────────────────
const lock = join(HOME, 'dispatch.lock');
if (!existsSync(lock)) {
    check('no dispatch lock held', true, 'idle');
} else {
    const ageMs = Date.now() - statSync(lock).mtimeMs;
    const ageMin = Math.round(ageMs / 60_000);
    check('no dispatch lock held', ageMs < STALE_LOCK_MS, ageMs < STALE_LOCK_MS ? `held ${ageMin}m (a cycle is running)` : `stale ${ageMin}m — a cycle died; delete ${lock}`);
}

// ── the ledger is the warlock's memory ────────────────────────────────────
const ledger = join(HOME, 'runs.jsonl');
const ledgerBody = read(ledger);
if (ledgerBody === null) {
    check('ledger readable', false, `${ledger} missing — no run history, fix-sweeps will skip every PR`);
} else {
    const bad = ledgerBody.split('\n').filter(Boolean).filter((l) => {
        try {
            JSON.parse(l);
            return false;
        } catch {
            return true;
        }
    }).length;
    check('ledger readable', bad === 0, bad ? `${bad} unparseable line(s) in ${ledger}` : `${ledgerBody.split('\n').filter(Boolean).length} run(s)`);
}

// ── without 9router the warlock skips every cycle ─────────────────────────
const router = resolveRouter();
const base = router.baseUrl;
try {
    const r = await fetch(`${base}/messages`, {
        method: 'POST',
        signal: AbortSignal.timeout(15_000),
        headers: { 'content-type': 'application/json', 'x-api-key': router.key || '', 'anthropic-version': '2023-06-01' },
        body: JSON.stringify({ model: 'MAX', max_tokens: 5, stream: false, messages: [{ role: 'user', content: 'say ok' }] }),
    });
    check('9router answers a MAX probe', r.ok, `${base} → ${r.status} (${describeRouter(router)})`);
} catch (e) {
    check('9router answers a MAX probe', false, `${base} → ${e.message} (${describeRouter(router)})`);
}

// ── report ────────────────────────────────────────────────────────────────
const failed = results.filter((r) => !r.ok);
if (process.argv.includes('--json')) {
    console.log(JSON.stringify({ code: CODE, home: HOME, runner, results }, null, 2));
} else {
    for (const r of results) console.log(`${r.ok ? 'ok  ' : 'FAIL'}  ${r.name}${r.detail ? ` — ${r.detail}` : ''}`);
    console.log(failed.length ? `\n${failed.length} check(s) failed. Contract: imps/WARLOCK.md` : '\nOne warlock, many imps. Topology is sane.');
}
process.exit(failed.length ? 1 : 0);
